    constexpr auto NativeMenuWindowIndex(std::string_view resource, const uint8_t variant = 0) -> size_t
    {
        if (resource == "aucmain ") resource = "auc1    ";
        if (resource == "statcom2") resource = "statcom ";
        if (resource == "level   ") resource = "persona ";
        if (resource == "mcr1long") resource = "mcr1pall";
        if (resource == "mcr2long") resource = "mcr2pall";
        if (resource == "mcr1edlo") resource = "mcr1edit";
        if (resource == "mcr2edlo") resource = "mcr2edit";
        if (resource == "prty5us ") resource = "prty5   ";
        if (resource == "prty5fr ") resource = "prty5   ";
        if (resource == "prty5de ") resource = "prty5   ";
        if (resource == "resynus ") resource = "resyn   ";
        if (resource == "resynfr ") resource = "resyn   ";
        if (resource == "resynde ") resource = "resyn   ";
        if (resource == "map0    ") resource = "mapframe";
        if (resource == "mapv3   ") resource = "mapframe";
        if (resource == "mapv2   ") resource = "mapframe";
        if (resource == "jobcselu") resource = "jobcsel ";
        for (size_t index = 0; index < std::size(native_menu_windows); ++index)
            if (resource == native_menu_windows[index].resource && native_menu_windows[index].variant == variant) return index;
        return std::size(native_menu_windows);
    }
