"""Validate UTF-8 locale catalogs and compile them into the standalone DLL."""

import argparse
import json
from pathlib import Path
import re

from localization_sources import referenced_messages

ROOT = Path(__file__).resolve().parents[1]
FORMAT = re.compile(r"%(?:[-+#0]*\d*(?:\.\d+)?(?:hh|ll|[hljztL]|I64|I32)?[diuoxXfFeEgGaAcspn]|%)")


def read_catalog(path):
    def unique(pairs):
        result = {}
        for key, value in pairs:
            if key in result:
                raise ValueError(f"{path}: duplicate message {key!r}")
            if not isinstance(value, str) or not value or "\0" in key + value:
                raise ValueError(f"{path}: invalid message {key!r}")
            result[key] = value
        return result
    return json.loads(path.read_text(encoding="utf-8"), object_pairs_hook=unique)


def literal(text):
    # ASCII source keeps MSVC's execution character set out of the UTF-8 path.
    return '"' + ''.join(f"\\{byte:03o}" for byte in text.encode("utf-8")) + '"'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    english = read_catalog(ROOT / "locales/en.json")
    japanese = read_catalog(ROOT / "locales/ja.json")
    if english.keys() != japanese.keys():
        raise ValueError(f"Locale keys differ: {english.keys() ^ japanese.keys()}")
    for label in ("HP", "MP", "TP"):
        if english.get(label) != label or japanese.get(label) != label:
            raise ValueError(f"Resource abbreviation must stay unchanged in both locales: {label}")
    for index in range(1, 11):
        key = f"Hotbar {index}"
        if japanese.get(key) != japanese["Hotbar"] + str(index):
            raise ValueError(f"Numbered Hotbar labels must use the same translation: {key}")
    if japanese.get("Hotbar %zu") != japanese["Hotbar"] + "%zu":
        raise ValueError("The numbered Hotbar template must match the static labels")
    missing = {key: location for key, location in referenced_messages(ROOT).items() if key not in english}
    if missing:
        details = "\n".join(f"{location}: {key!r}" for key, location in sorted(missing.items()))
        raise ValueError(f"Messages missing from both locale catalogs:\n{details}")
    for key, value in english.items():
        if key != value:
            raise ValueError(f"English message must match its source key: {key!r}")
        if FORMAT.findall(value) != FORMAT.findall(japanese[key]):
            raise ValueError(f"Format arguments differ: {key!r}")
    if args.output:
        rows = ["// Generated by scripts/build-locales.py. Edit locales/*.json.", "#pragma once",
                "namespace xiui::i18n {", "struct catalog_entry { const char* english; const char* japanese; };",
                "inline constexpr catalog_entry catalog[]{"]
        rows += [f"    {{{literal(key)}, {literal(japanese[key])}}}," for key in sorted(english)]
        rows += ["};", "}", ""]
        output = "\n".join(rows)
        args.output.parent.mkdir(parents=True, exist_ok=True)
        if not args.output.exists() or args.output.read_text(encoding="ascii") != output:
            args.output.write_text(output, encoding="ascii")
    print(f"Locales: {len(english)} matching English/Japanese messages; source coverage, resource labels, Hotbar consistency and format arguments verified.")


if __name__ == "__main__":
    main()
