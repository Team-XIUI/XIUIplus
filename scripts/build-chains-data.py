"""Generate pet availability metadata from the pinned Chains pet table."""

import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/chains/pets.lua"


def main():
    text = SOURCE.read_text(encoding="utf-8-sig")
    jugs, frames = text.split("pets.frames =", 1)
    output = ["#pragma once", "", "// Generated by scripts/build-chains-data.py; see assets/chains/NOTICES.txt.",
              "#include <array>", "#include <cstdint>", "#include <string_view>", "", "namespace xiui::resources", "{",
              "    struct chains_jug_move { std::string_view pet, move; };",
              "    struct chains_frame_move { uint8_t frame; uint16_t id, skill; bool ranged; };"]
    rows = []
    for block in re.finditer(r"(?:\['([^']+)'\]|(\w+))\s*=\s*\{([^{}]+)\}", jugs):
        pet = (block[1] or block[2])[:15]
        for move in re.finditer(r"\[\d+\]\s*=\s*true,\s*--\s*([^\n\r]+)", block[3]):
            rows.append(f"        {{{json.dumps(pet)}, {json.dumps(move[1].strip())}}},")
    output += [f"    inline constexpr std::array<chains_jug_move, {len(rows)}> chains_jug_moves{{{{", *rows, "    }};"]
    rows = []
    for block in re.finditer(r"\w+\s*=\s*\{([^}]+)\}", frames):
        frame = int(re.search(r"item\s*=\s*(\d+)", block[1])[1]) - 0x2000
        ranged = "true" if "ranged = true" in block[1] else "false"
        for move in re.finditer(r"\[(\d+)\]\s*=\s*(\d+)", block[1]):
            rows.append(f"        {{{frame}, {move[1]}, {move[2]}, {ranged}}},")
    output += [f"    inline constexpr std::array<chains_frame_move, {len(rows)}> chains_frame_moves{{{{", *rows, "    }};", "}"]
    (ROOT / "src/runtime/resources/chains_data.hpp").write_text("\n".join(output) + "\n", encoding="utf-8")
    print(f"Chains pet metadata generated; pets.lua SHA256 {hashlib.sha256(SOURCE.read_bytes()).hexdigest()}")


if __name__ == "__main__":
    main()
