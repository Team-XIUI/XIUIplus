"""Bake the original XIUI GitHub icon into the shared native icon atlas mask."""

from pathlib import Path
from PIL import Image

root = Path(__file__).resolve().parents[1]
alpha = Image.open(root / "assets/icons/github.png").convert("RGBA").resize((128, 128), Image.Resampling.LANCZOS).getchannel("A")
runs = []
for value in alpha.tobytes():
    if runs and runs[-1][1] == value:
        runs[-1][0] += 1
    else:
        runs.append([1, value])
values = [f"0x{(count << 8) | value:08X}" for count, value in runs]
rows = ["        " + ", ".join(values[index:index + 10]) + "," for index in range(0, len(values), 10)]
header = """#pragma once

#include <cstdint>

// Generated by scripts/build-github-icon.py from assets/icons/github.png.
namespace xiui::resources
{
    inline constexpr uint32_t github_icon_runs[]{
""" + "\n".join(rows) + "\n    };\n}\n"
(root / "src/runtime/resources/github_icon.hpp").write_text(header, encoding="utf-8")
