"""Bake original XIUI's target arrow into the native icon atlas mask."""

from pathlib import Path
from PIL import Image, ImageChops

root = Path(__file__).resolve().parents[1]
source = Image.open(root / "assets/icons/target-arrow.png").convert("RGBA")
mask = ImageChops.multiply(source.convert("L"), source.getchannel("A"))
mask = mask.resize((128, 128), Image.Resampling.LANCZOS)
runs = []
for value in mask.tobytes():
    if runs and runs[-1][1] == value:
        runs[-1][0] += 1
    else:
        runs.append([1, value])
values = [f"0x{(count << 8) | value:08X}" for count, value in runs]
rows = ["        " + ", ".join(values[i:i + 10]) + "," for i in range(0, len(values), 10)]
header = """#pragma once

#include <cstdint>

// Generated by scripts/build-target-arrow.py from assets/icons/target-arrow.png.
namespace xiui::resources
{
    inline constexpr uint32_t target_arrow_runs[]{
""" + "\n".join(rows) + "\n    };\n}\n"
(root / "src/runtime/resources/target_arrow.hpp").write_text(header, encoding="utf-8")
