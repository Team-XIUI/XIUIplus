"""Generate native defaults and coverage inventory from release-writer fixtures."""

import argparse
import json
from pathlib import Path


def leaves(data, prefix=""):
    if not isinstance(data, dict) or not data:
        yield prefix, data
    else:
        for key, value in sorted(data.items()):
            yield from leaves(value, f"{prefix}.{key}" if prefix else key)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--inventory", type=Path)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    lines = ["// Generated by scripts/build-lua-profile-schema.py.", "#pragma once", "#include <span>",
             "namespace xiui::lua_schema {", "struct field { const char* path; char type; const char* value; };" ]
    inventory = {}
    for version in ("1.8.4", "1.8.5"):
        data = json.loads((root / "tests/fixtures/lua" / version / "defaults.json").read_text(encoding="utf-8"))
        entries = list(leaves(data))
        inventory[version] = [{"path": path, "type": type(value).__name__, "default": value} for path, value in entries]
        lines.append(f"inline constexpr field defaults_{version.replace('.', '')}[]{{")
        for path, value in entries:
            kind = "t" if isinstance(value, dict) else "b" if isinstance(value, bool) else "n" if isinstance(value, (int, float)) else "s"
            text = "" if kind == "t" else str(value).lower() if kind == "b" else str(value)
            lines.append("{" + json.dumps(path, ensure_ascii=True) + ", '" + kind + "', " + json.dumps(text, ensure_ascii=True) + "},")
        lines.append("};")
    lines.append("}")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    content = "\n".join(lines) + "\n"
    if not args.output.exists() or args.output.read_text(encoding="utf-8") != content:
        args.output.write_text(content, encoding="utf-8")
    if args.inventory:
        args.inventory.parent.mkdir(parents=True, exist_ok=True)
        args.inventory.write_text(json.dumps(inventory, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
