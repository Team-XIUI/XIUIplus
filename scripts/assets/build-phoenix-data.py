"""Generate Phoenix ToAU roll and spawn-slot data from pinned server sources."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / "assets/phoenix"
COMMIT = "11c6ee57720a8c6fd79c0fd46ff38ea8e074bf5e"


def table(text, marker):
    start = text.index("{", text.index(marker))
    depth = 0
    for end in range(start, len(text)):
        depth += (text[end] == "{") - (text[end] == "}")
        if depth == 0:
            return text[start:end + 1]
    raise ValueError(marker)


def powers(text):
    return {name: [float(value) for value in values.split(",") if value.strip()]
        for name, values in re.findall(r"\[xi\.jobAbility\.(\w+)\]\s*=\s*\{\s*(?:effect\s*=\s*[^,]+,\s*)?powers\s*=\s*\{([^}]+)\}", text)}


JOBS = "NONE WAR MNK WHM BLM RDM THF PLD DRK BST BRD RNG SAM NIN DRG SMN BLU COR PUP DNC SCH GEO RUN".split()


def bonuses(text):
    """Return {ability: (job, bonus)}; a missing bonusJob keeps the earlier value."""
    result = {}
    for name, body in re.findall(r"\[xi\.jobAbility\.(\w+)\]\s*=\s*\{((?:[^{}]|\{[^{}]*\})*)\}", text):
        bonus = re.search(r"\bbonus\s*=\s*(-?\d+)", body)
        job = re.search(r"\bbonusJob\s*=\s*xi\.job\.(\w+)", body)
        if bonus:
            result[name] = (JOBS.index(job[1]) if job else None, int(bonus[1]))
    return result


def rolls():
    source = (ASSETS / "source/scripts__globals__job_utils__corsair.lua").read_text(encoding="utf-8-sig")
    era = (ASSETS / "source/modules__era__lua__globals__job_utils__corsair.lua").read_text(encoding="utf-8-sig")
    values = powers(table(source, "xi.job_utils.corsair.rollData ="))
    jobs = bonuses(table(source, "xi.job_utils.corsair.rollData ="))
    for marker in ("local soaRollData", "local abysseaRollData"):
        values.update(powers(table(era, marker)))
        for key, (job, bonus) in bonuses(table(era, marker)).items():
            jobs[key] = (jobs[key][0] if job is None else job, bonus)
    native = (ROOT / "src/runtime/modules/phantomroll/phantom_roll_data.cpp").read_text(encoding="utf-8-sig").split("constexpr std::array<xiui::phantom_roll_data, 31> horizon", 1)[0]
    result = []
    pattern = r'\{"([^"]+)", (\d+), (\d+), (\d+), (\d+), "([^"]+)", (true|false), (true|false), (true|false), (\d+), \{([^}]+)\}(?:, \d+, -?\d+)?\}'
    for name, ability, status, lucky, unlucky, stat, percent, unknown, per_level, scale, previous in re.findall(pattern, native):
        key = re.sub(r"[^A-Z]", "", name.upper()) + "_ROLL"
        if key not in values:
            raise ValueError(f"Missing Phoenix roll {key}")
        raw = values[key][:11]
        if len(raw) != 11:
            raise ValueError(key)
        if name == "Healer's": stat, percent = "hMP", "false"
        if name == "Gallant's": stat, percent = "Dmg reflect", "true"
        if name == "Drachen": stat, percent = "Pet MAB/MACC", "false"
        if name == "Puppet": stat, percent = "Pet ACC", "false"
        scale = 100 if any(value != int(value) for value in raw) else 1
        packed = [round(value * scale) for value in raw] + [0]
        # Phoenix grants rolls without a bonus job their bonus only through gear, which stays unknown.
        job, bonus = jobs[key]
        if job is None or job == 0 or bonus == 0: job = bonus = 0
        result.append(f'        {{"{name}", {ability}, {status}, {lucky}, {unlucky}, "{stat}", {percent}, {unknown}, false, {scale}, {{{", ".join(map(str, packed))}}}, {job}, {bonus * scale}}},')
    if len(result) != 31:
        raise ValueError(f"Expected 31 rolls, found {len(result)}")
    header = '#pragma once\n\n// Generated by scripts/assets/build-phoenix-data.py.\nnamespace xiui::resources\n{\n    inline constexpr std::array<phantom_roll_data, 31> phoenix_rolls{{\n' + "\n".join(result) + '\n    }};\n}\n'
    (ROOT / "src/runtime/resources/phoenix_roll_data.hpp").write_text(header, encoding="utf-8")


def spawn_slots(source):
    import yaml
    slots, hashes = {}, {}
    paths = list(sorted((source / "data/zones").glob("*/mobs.yaml")))
    paths += list(sorted((source / "modules/phoenix/data/zones").glob("*/mobs.yaml")))
    paths += list(sorted((source / "modules/phoenix/data/nm_respawn/zones").glob("*/mobs.yaml")))
    for path in paths:
        data = yaml.safe_load(path.read_text(encoding="utf-8-sig")) or {}
        if "slots" in data:
            slots[path.parent.name] = data["slots"]
            hashes[str(path.relative_to(source)).replace("\\", "/")] = hashlib.sha256(path.read_bytes()).hexdigest()
    edges = set()
    for zone, groups in slots.items():
        for group in groups:
            members = group.get("members", {})
            candidates = [(int(key), value or {}) for key, value in members.items() if isinstance(key, int)]
            normal = [key for key, value in candidates if not value.get("chance", 0)]
            for target, value in candidates:
                chance = int(value.get("chance", 0))
                if chance <= 0:
                    continue
                cooldown = int(value.get("cooldown", 0))
                edges.add((target, target, chance, cooldown, False))
                for placeholder in normal:
                    edges.add((placeholder, target, chance, cooldown, True))
    payload = {"phoenix_commit": COMMIT, "profile": "Phoenix ToAU (75 cap)", "source_sha256": hashes, "relations": sorted(edges)}
    (ASSETS / "spawn_slots.json").write_text(json.dumps(payload, separators=(",", ":")) + "\n", encoding="utf-8")


def emit_spawns():
    payload = json.loads((ASSETS / "spawn_slots.json").read_text())
    rows = [f'        {{{member}u, {target}u, {chance}, {cooldown}u, {str(placeholder).lower()}}},' for member, target, chance, cooldown, placeholder in payload["relations"]]
    header = '#pragma once\n\n#include <array>\n#include <cstdint>\n\nnamespace xiui::resources\n{\n    struct phoenix_spawn_relation { uint32_t member, target; uint16_t chance; uint32_t cooldown; bool placeholder; };\n'
    header += f'    inline constexpr std::array<phoenix_spawn_relation, {len(rows)}> phoenix_spawn_relations{{{{\n' + "\n".join(rows) + '\n    }};\n}\n'
    (ROOT / "src/runtime/resources/phoenix_spawn_data.hpp").write_text(header, encoding="utf-8")
    print(f"Phoenix: 31 roll records, {len(rows)} spawn relationships")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path)
    args = parser.parse_args()
    rolls()
    if args.source:
        spawn_slots(args.source)
    emit_spawns()
    manifest = {"phoenix_commit": COMMIT, "profile": "Phoenix ToAU (75 cap)", "source": "https://github.com/phoenixffxi/Phoenix", "settings_source": "https://github.com/Tanyrus/headsup/blob/161ad60f7d0ed10fd5b71a6889bd777a43d5dc7b/tools/phoenix/live_settings.lua", "sha256": {path.name: hashlib.sha256(path.read_bytes()).hexdigest() for path in sorted((ASSETS / "source").iterdir())}}
    (ASSETS / "sources.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
