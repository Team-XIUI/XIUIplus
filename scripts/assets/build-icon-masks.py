"""Bake original XIUI's GitHub icon and target arrow into run-length masks for the native icon atlas."""

from pathlib import Path

from PIL import Image, ImageChops


ROOT = Path(__file__).resolve().parents[2]


def bake(source_name, header_name, symbol, luminance):
    source = Image.open(ROOT / "assets/icons" / source_name).convert("RGBA")
    # The arrow's shape lives in its luminance; the GitHub icon is alpha only.
    mask = ImageChops.multiply(source.convert("L"), source.getchannel("A")) if luminance else source
    mask = mask.resize((128, 128), Image.Resampling.LANCZOS)
    if not luminance:
        mask = mask.getchannel("A")
    runs = []
    for value in mask.tobytes():
        if runs and runs[-1][1] == value:
            runs[-1][0] += 1
        else:
            runs.append([1, value])
    values = [f"0x{(count << 8) | value:08X}" for count, value in runs]
    rows = ["        " + ", ".join(values[index:index + 10]) + "," for index in range(0, len(values), 10)]
    header = f"""#pragma once

#include <cstdint>

// Generated by scripts/assets/build-icon-masks.py from assets/icons/{source_name}.
namespace xiui::resources
{{
    inline constexpr uint32_t {symbol}[]{{
""" + "\n".join(rows) + "\n    };\n}\n"
    (ROOT / "src/runtime/resources" / header_name).write_text(header, encoding="utf-8")


bake("github.png", "github_icon.hpp", "github_icon_runs", False)
bake("target-arrow.png", "target_arrow.hpp", "target_arrow_runs", True)
