"""Pack the checked-in XIUI status/job icon sources for the embedded runtime."""

from argparse import ArgumentParser
from io import BytesIO
from pathlib import Path
import shutil
import struct
from zipfile import ZIP_DEFLATED, ZipFile

from PIL import Image


ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / "assets/icon-themes"
PACKS = (("status", "HD", "status-hd"), ("status", "Tetsouou", "status-tetsouou"),
         ("status", "XIView", "status-xiview"), ("jobs", "Classic", "jobs-classic"),
         ("jobs", "FFXI", "jobs-ffxi"), ("jobs", "FFXIV-1", "jobs-ffxiv"))
JOBS = "war mnk whm blm rdm thf pld drk bst brd rng sam nin drg smn blu cor pup dnc sch geo run mon spc".split()


def capture(source):
    destination = ASSETS / "sources"
    destination.mkdir(parents=True, exist_ok=True)
    for kind, name, slug in PACKS:
        with ZipFile(destination / f"{slug}.zip", "w", ZIP_DEFLATED) as archive:
            for image in sorted((source / kind / name).iterdir()):
                if image.suffix.lower() == ".png" or image.name == "credits.txt":
                    archive.writestr(image.name, image.read_bytes())
    shutil.copyfile(source.parent.parent / "LICENSE", ASSETS / "LICENSE.txt")


def build():
    presence = []
    for kind, name, slug in PACKS:
        atlas = Image.new("RGBA", (1024, 1024) if kind == "status" else (512, 256))
        mask = bytearray(128)
        if kind == "jobs":
            for index, job in enumerate(JOBS):
                with Image.open(ROOT / "assets/jobs/xivparty" / f"{job}.png") as image:
                    atlas.paste(image.convert("RGBA"), ((index % 8) * 64, (index // 8) * 64))
        with ZipFile(ASSETS / "sources" / f"{slug}.zip") as archive:
            used = 0
            for filename in sorted(archive.namelist()):
                path = Path(filename)
                if path.suffix.lower() != ".png":
                    continue
                if kind == "status":
                    if not path.stem.isdecimal() or not 0 <= int(path.stem) <= 1023:
                        continue
                    index, cell, columns = int(path.stem), 32, 32
                    mask[index // 8] |= 1 << (index % 8)
                else:
                    if path.stem not in JOBS:
                        continue
                    index, cell, columns = JOBS.index(path.stem), 64, 8
                with Image.open(BytesIO(archive.read(filename))) as source:
                    image = source.convert("RGBA")
                if image.size != (cell, cell):
                    if kind == "status" and image.width <= cell and image.height <= cell:
                        padded = Image.new("RGBA", (cell, cell))
                        padded.paste(image, ((cell - image.width) // 2, (cell - image.height) // 2))
                        image = padded
                    elif kind == "jobs" and image.size == (32, 32):
                        image = image.resize((cell, cell), Image.Resampling.NEAREST)
                    else:
                        raise ValueError(f"Unexpected icon dimensions: {slug}/{filename}: {image.size}")
                atlas.paste(image, ((index % columns) * cell, (index // columns) * cell))
                used += 1
        (ASSETS / f"{slug}.bgra").write_bytes(struct.pack("<II", *atlas.size) + atlas.tobytes("raw", "BGRA"))
        if kind == "status":
            presence.append(mask)
        print(f"{slug}: {used} icons")
    lines = ["#pragma once", "", "#include <array>", "#include <cstdint>", "", "namespace xiui::resources", "{",
             "    // Generated by scripts/assets/build-icon-themes.py from the retained source PNGs.",
             "    inline constexpr std::array<std::array<uint8_t, 128>, 3> status_theme_presence{{"]
    for mask in presence:
        lines.append("        {{" + ",".join(str(value) for value in mask) + "}},")
    lines += ["    }};", "}", ""]
    (ROOT / "src/runtime/resources/icon_theme_art.hpp").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    parser = ArgumentParser()
    parser.add_argument("--import-from", type=Path, help="Capture source packs from the original XIUI assets directory.")
    args = parser.parse_args()
    ASSETS.mkdir(parents=True, exist_ok=True)
    if args.import_from:
        capture(args.import_from)
    build()
